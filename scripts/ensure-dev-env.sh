#!/usr/bin/env bash
# `npm run dev`/`npm start` use `node --env-file=.env`, which errors outright
# if the file doesn't exist at all (see AGENTS.md). This generates one, only
# when missing, so a fresh checkout (a CI runner, a fresh sandbox) can run
# the app/tests without a human copying .env.example by hand first.
#
# Every value below is a throwaway dummy — this is meant for local/CI test
# runs, never a real deployment. Never commit the .env this writes (already
# gitignored). Safe to re-run: does nothing if .env already exists, so it
# never clobbers real values a developer set up themselves.
set -euo pipefail
cd "$(dirname "$0")/.."

if [[ -f .env ]]; then
  exit 0
fi

SECRET=$(node -e "console.log(require('crypto').randomBytes(32).toString('hex'))")

cat > .env << EOF
# Auto-generated by scripts/ensure-dev-env.sh — dummy values only, see that
# script's header comment. Delete freely to regenerate; never commit.
SECRET=$SECRET
SITE_PASSWORD=e2e-host-password
FRIEND_PASSWORD=e2e-friend-password
PORT=3000
DEV_WS_PORT=3001
HTTPS=false
FORCE_HTTPS=false
DB_PATH=./data/rooms.db
ROOM_MAX_AGE_HOURS=12
FRIEND_ROOM_MAX_AGE_HOURS=12
ROOM_STATE_GRACE_MS=10000
MAX_POSTS_PER_MIN=20
MAX_AUTH_POSTS_PER_MIN=10
# Deliberately blank: AI-path tests should hit the safe "not configured"
# branch, never make a real, paid OpenRouter call.
OPENROUTER_API_KEY=
RESEARCH_EVAL_LOG=false
EOF

echo "ensure-dev-env: wrote a throwaway .env (dummy values, gitignored)"
